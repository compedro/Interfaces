    private java.awt.Font cargarFuente(String ruta) {
        try {
            java.io.InputStream is = getClass().getResourceAsStream(ruta);
            java.awt.Font fuente = java.awt.Font.createFont(java.awt.Font.TRUETYPE_FONT, is);
            java.awt.GraphicsEnvironment ge = java.awt.GraphicsEnvironment.getLocalGraphicsEnvironment();
            ge.registerFont(fuente);
            return fuente;
        } catch (Exception e) {
            logger.log(java.util.logging.Level.SEVERE, "Error cargando fuente: " + ruta, e);
            return new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12);
        }
    }




    private void ajustarImagen(javax.swing.JLabel lbl, String ruta) {
        javax.swing.ImageIcon imagen = new javax.swing.ImageIcon(ruta);
        java.awt.Image imgEscalada = imagen.getImage().getScaledInstance(
                lbl.getWidth(),
                lbl.getHeight(),
                java.awt.Image.SCALE_SMOOTH
        );
        lbl.setIcon(new javax.swing.ImageIcon(imgEscalada));
        this.repaint();
    }

